const cur = () => MAIN.find(([c]) => c());
export function objective() { return cur()[1]; }
// where the minimap should point on this map: an exit toward the next map of the route, or the place itself
export function target(M) {
  const [, , route, spot] = cur(); if (!route?.length) return null;
  const id = M.def.id, i = route.indexOf(id);
  const exitTo = (to) => { if (to === 'whitehawk_r') to = 'whitehawk'; const e = M.exits.find((e) => e.to === to || e.loc === to || (to === 'world' && e.to === 'world')); return e ? { x: (e.x0 + e.x1) / 2, z: (e.z0 + e.z1) / 2, kind: 'exit' } : null; };
  if (i === route.length - 1) { const s = M.spots[spot]; if (s) return { x: s.x, z: s.z, kind: 'goal' }; return { npc: spot, kind: 'goal' }; }
  if (i >= 0) return exitTo(route[i + 1]);
  // not on the route: head for the world map, or on the world map for the first place of the route
  if (M.world) return exitTo(route.find((r) => r !== 'world'));
  return exitTo('world') || exitTo(route[0]);
}

